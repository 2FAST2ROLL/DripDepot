/* =========================================
   BRAND FILTER
========================================= */

document.querySelectorAll(".brand-list button")
  .forEach(button => {

    button.addEventListener("click", () => {

      document.querySelectorAll(".brand-list button")
        .forEach(btn => btn.classList.remove("active"));

      button.classList.add("active");

      const brand = button.dataset.brand;

      if (brand === "All") {

        searchInput.value = "";

      } else {

        searchInput.value = brand;

      }

      renderProducts();

    });

  });


